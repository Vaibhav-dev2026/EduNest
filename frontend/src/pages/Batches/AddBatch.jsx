import { useState, useEffect } from "react";
import { useNavigate } from "react-router-dom";

import AdminLayout from "../../layouts/AdminLayout";
import PageHeader from "../../components/common/PageHeader";
import Button from "../../components/common/Button";
import Input from "../../components/common/Input";

import { addBatch } from "../../services/batchService";
import { getCourses } from "../../services/courseService";
import { getTeachers } from "../../services/teacherService";

function AddBatch() {

    const navigate = useNavigate();

    const [batch, setBatch] = useState({
        batchName: "",
        course: "",
        teacher: "",
        startDate: "",
        endDate: "",
        timing: "",
        room: "",
        maxStudents: "",
        status: "Active",
        description: ""
    });

    const [courses, setCourses] = useState([]);
    const [teachers, setTeachers] = useState([]);

    const [errors, setErrors] = useState({});
    const [isSaving, setIsSaving] = useState(false);
    const [apiError, setApiError] = useState(null);
    const [apiSuccess, setApiSuccess] = useState(null);

    useEffect(() => {
        getCourses().then(setCourses).catch(() => setCourses([]));
        getTeachers().then(setTeachers).catch(() => setTeachers([]));
    }, []);

    const handleChange = (event) => {

        const { name, value } = event.target;

        setBatch((previous) => ({

            ...previous,

            [name]: value

        }));

    };

    const validateForm = () => {

        let validationErrors = {};

        if (batch.batchName.trim() === "") {

            validationErrors.batchName = "Batch Name is required";

        }

        if (batch.course === "") {

            validationErrors.course = "Please Select Course";

        }

        if (!batch.teacherId || batch.teacherId === "") {

            validationErrors.teacher = "Please Select Teacher";

        }

        setErrors(validationErrors);

        return Object.keys(validationErrors).length === 0;

    };

    const handleSubmit = async (event) => {
        event.preventDefault();
        setApiError(null);
        setApiSuccess(null);

        if (!validateForm()) return;

        setIsSaving(true);
        try {
            await addBatch(batch);
            setApiSuccess("Batch Added Successfully");
            setTimeout(() => navigate("/batches"), 1500);
        } catch (error) {
            console.log(error);
            setApiError(error.message || "Failed To Add Batch");
            setIsSaving(false);
        }
    };
        return (

        <AdminLayout>

            <PageHeader
                title="Add Batch"
                subtitle="Create New Batch"
            />

            <div className="card shadow-sm">
                <div className="card-body">
                    {apiError && <div className="alert alert-danger">{apiError}</div>}
                    {apiSuccess && <div className="alert alert-success">{apiSuccess}</div>}
                    <form onSubmit={handleSubmit}>

                        <div className="row">

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Batch Code
                                </label>

                                <Input
                                    type="text"
                                    value="Auto-Generated by Server"
                                    readOnly
                                    className="bg-light text-muted"
                                />

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Batch Name
                                </label>

                                <Input
                                    type="text"
                                    name="batchName"
                                    value={batch.batchName}
                                    onChange={handleChange}
                                    placeholder="Enter Batch Name"
                                />

                                {
                                    errors.batchName &&
                                    <small className="text-danger">
                                        {errors.batchName}
                                    </small>
                                }

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Course
                                </label>

                                <select
                                    className="form-select"
                                    name="course"
                                    value={batch.course}
                                    onChange={handleChange}
                                >
                                    <option value="">Select Course</option>
                                    {courses.map((c, i) => (
                                        <option key={c._id || i} value={c.courseName || c.name}>
                                            {c.courseName || c.name}
                                        </option>
                                    ))}
                                </select>

                                {
                                    errors.course &&
                                    <small className="text-danger">
                                        {errors.course}
                                    </small>
                                }

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Teacher
                                </label>

                                <select
                                    className="form-select"
                                    name="teacherId"
                                    value={batch.teacherId || ""}
                                    onChange={handleChange}
                                >
                                    <option value="">Select Teacher</option>
                                    {teachers.map((t, i) => (
                                        <option key={t._id || i} value={t.teacherId}>
                                            {`${t.firstName || ""} ${t.lastName || ""}`.trim() || t.teacherId}
                                        </option>
                                    ))}
                                </select>

                                {
                                    errors.teacher &&
                                    <small className="text-danger">
                                        {errors.teacher}
                                    </small>
                                }

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Start Date
                                </label>

                                <Input
                                    type="date"
                                    name="startDate"
                                    value={batch.startDate}
                                    onChange={handleChange}
                                />

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    End Date
                                </label>

                                <Input
                                    type="date"
                                    name="endDate"
                                    value={batch.endDate}
                                    onChange={handleChange}
                                />

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Batch Timing
                                </label>

                                <Input
                                    type="text"
                                    name="timing"
                                    value={batch.timing}
                                    onChange={handleChange}
                                    placeholder="09:00 AM - 11:00 AM"
                                />

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Room Number
                                </label>

                                <Input
                                    type="text"
                                    name="room"
                                    value={batch.room}
                                    onChange={handleChange}
                                    placeholder="Room No."
                                />

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Maximum Students
                                </label>

                                <Input
                                    type="number"
                                    name="maxStudents"
                                    value={batch.maxStudents}
                                    onChange={handleChange}
                                />

                            </div>

                            <div className="col-md-6 mb-3">

                                <label className="form-label">
                                    Status
                                </label>

                                <select
                                    className="form-select"
                                    name="status"
                                    value={batch.status}
                                    onChange={handleChange}
                                >

                                    <option value="Active">
                                        Active
                                    </option>

                                    <option value="Inactive">
                                        Inactive
                                    </option>

                                </select>

                            </div>

                            <div className="col-12 mb-3">

                                <label className="form-label">
                                    Description
                                </label>

                                <textarea
                                    className="form-control"
                                    rows="4"
                                    name="description"
                                    value={batch.description}
                                    onChange={handleChange}
                                    placeholder="Batch Description"
                                ></textarea>

                            </div>

                        </div>
                                                <div className="d-flex gap-2 mt-4">

                            <Button
                                type="submit"
                                text={isSaving ? "Saving..." : "Save Batch"}
                                className="btn btn-primary"
                                disabled={isSaving}
                            />

                            <Button
                                type="reset"
                                text="Reset"
                                className="btn btn-warning"
                                disabled={isSaving}
                            />

                            <Button
                                type="button"
                                text="Cancel"
                                className="btn btn-secondary"
                                onClick={() => navigate("/batches")}
                                disabled={isSaving}
                            />

                        </div>

                    </form>

                </div>

            </div>

        </AdminLayout>

    );

}

export default AddBatch;